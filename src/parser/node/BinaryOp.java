package parser.node;

/**
 * Enumerates the supported binary operators in the AST.
 */
public enum BinaryOp {
    /** Addition (+). */
    PLUS, 
    /** Subtraction (-). */
    SUBTRACT,
    /** Multiplication (*). */
    MULTIPLY,
    /** Division (/). */
    DIVIDE,
    /** Exponentiation (^). */
    POWER
}
